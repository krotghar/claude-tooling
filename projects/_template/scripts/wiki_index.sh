#!/usr/bin/env bash
# SessionStart-хук: кладёт каталог локальной wiki проекта в контекст сессии,
# чтобы сначала смотреть уже накопленные страницы, а потом лезть в репозиторий.
# Wiki живёт вне гит-репозитория, в каталоге данных обвязки ($CLAUDE_DATA).
#
# Прописан в ~/.claude/settings.json, то есть на уровне пользователя, а не
# проекта. Причина: воркtree, которые создаёт сам Claude Code
# (<репо>/.claude/worktrees/...), не получают проектный .claude/settings.json —
# там проектные хуки не срабатывают вообще. Пользовательский переживает любой
# воркtree. Плата — хук зовётся во всех проектах, поэтому ниже гард по репо.
set -uo pipefail

# Гард по репозиторию. Имя проекта — basename ГЛАВНОГО воркtree (как в link.sh),
# а не cwd, чтобы сработало и из соседнего воркtree, и из .claude/worktrees/*.
# Не гит / нет вики под проект — молча выходим.
cwd="${CLAUDE_PROJECT_DIR:-$PWD}"
main_worktree="$(git -C "$cwd" worktree list --porcelain 2>/dev/null | awk '/^worktree /{print $2; exit}')"
[ -n "$main_worktree" ] || exit 0

PROJECT="$(basename "$main_worktree")"
WIKI_DIR="${CLAUDE_DATA:-<DataRoot>}/projects/$PROJECT/wiki"
INDEX="$WIKI_DIR/index.md"

# Wiki может быть недоступна (другая машина, данные ещё не синкнулись) — тоже молча.
[ -r "$INDEX" ] || exit 0

cat <<EOF
Локальная wiki проекта (вне git): $WIKI_DIR
Страницы: $WIKI_DIR/pages/<slug>.md, схема: $WIKI_DIR/CLAUDE.md

Это шаг рабочего порядка, а не подсказка: ДО первого поиска по репозиторию —
до Grep/Glob и до чтения файлов ради «понять, как тут устроено» — сверься с
каталогом ниже и прочитай подходящие pages/<slug>.md целиком.

Триггер — не «вопрос по архитектуре» (задачи так себя не называют и правило не
срабатывает), а простой: собираешься разбираться в незнакомой части проекта →
сначала страница, потом репозиторий. Задача вида «реализуй X в разделе Y» под
него попадает.

Как это уживается с правилом «сверься с источником истины»: страница говорит,
КУДА смотреть и какие грабли уже известны; код, макет и project CLAUDE.md
подтверждают, ЧТО там сейчас. Wiki не отменяет проверку по коду — она убирает
слепой поиск перед ней. Расходится страница с кодом — прав код, а страницу
поправь.

EOF

cat "$INDEX"
